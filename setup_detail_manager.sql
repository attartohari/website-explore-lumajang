-- A. DETAIL CONFIGURATION COLUMN
-- Stores layout order, active sections, and rich text blocks not covered by standard columns
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'detail_config') THEN
        ALTER TABLE destinations ADD COLUMN detail_config JSONB DEFAULT '{}'::jsonb;
    END IF;
    
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'facilities') THEN
        ALTER TABLE destinations ADD COLUMN facilities TEXT[];
    END IF;
END $$;

-- B. PHOTO SPOTS TABLE (For Gallery/Spots Section)
CREATE TABLE IF NOT EXISTS photo_spots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT REFERENCES destinations(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    image_path TEXT,
    description TEXT,
    best_time TEXT,
    location_hint TEXT, -- e.g. "Near entrance"
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- C. NEARBY PLACES (For Culinary/Basecamp)
CREATE TABLE IF NOT EXISTS nearby_places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT REFERENCES destinations(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT CHECK (type IN ('culinary', 'lodging', 'souvenir', 'basecamp', 'other')),
    distance TEXT, -- e.g "500m"
    note TEXT, -- Recommendation note
    maps_url TEXT,
    image_path TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- D. VISITOR TIPS (Optional, can also just be in detail_config JSON)
