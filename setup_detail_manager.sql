-- We will store them in `detail_config` -> `tips` array.

-- RLS
ALTER TABLE photo_spots ENABLE ROW LEVEL SECURITY;
ALTER TABLE nearby_places ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read spots" ON photo_spots FOR SELECT USING (true);
CREATE POLICY "Public read nearby" ON nearby_places FOR SELECT USING (true);
CREATE POLICY "Admin all spots" ON photo_spots USING (auth.role() = 'authenticated');
CREATE POLICY "Admin all nearby" ON nearby_places USING (auth.role() = 'authenticated');

