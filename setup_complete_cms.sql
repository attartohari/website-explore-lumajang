-- CLEANUP OLD POLICIES (To ensure idempotency)
DO $$ 
DECLARE 
    r RECORD;
BEGIN 
    FOR r IN (SELECT policyname, tablename FROM pg_policies WHERE schemaname = 'public') LOOP 
        EXECUTE 'DROP POLICY IF EXISTS "' || r.policyname || '" ON ' || r.tablename; 
    END LOOP; 
END $$;

-- PUBLIC READ ACCESS (The Website)
CREATE POLICY "Public read destinations" ON destinations FOR SELECT USING (status = 'published' OR true); -- 'OR true' temporarily for dev visibility if status null, ideally status='published'
CREATE POLICY "Public read spots" ON photo_spots FOR SELECT USING (true);
CREATE POLICY "Public read nearby" ON nearby_places FOR SELECT USING (true);
CREATE POLICY "Public read page_sections" ON page_sections FOR SELECT USING (true);
CREATE POLICY "Public read articles" ON articles FOR SELECT USING (status = 'published');
CREATE POLICY "Public read checklists" ON checklists FOR SELECT USING (true);
CREATE POLICY "Public read playlists" ON playlists FOR SELECT USING (true);
CREATE POLICY "Public read playlist_items" ON playlist_items FOR SELECT USING (true);

-- PUBLIC WRITE ACCESS (Forms)
CREATE POLICY "Public insert contact" ON contact_messages FOR INSERT WITH CHECK (true);
CREATE POLICY "Public insert newsletter" ON newsletter_subscribers FOR INSERT WITH CHECK (true);
CREATE POLICY "Public read user_roles" ON user_roles FOR SELECT USING (true); -- Needed for auth check on client


-- AUTHENTICATED USER ACCESS (Favorites)
CREATE POLICY "Users manage own favorites" ON favorites FOR ALL USING (auth.uid() = user_id);

-- ADMIN FULL ACCESS
-- Assuming admin has 'authenticated' role for MVP. 
-- Ideally check for specific claim or user_roles table, but simplifying to 'authenticated' as per existing login flow 
-- which effectively gates 'admin' pages nicely.
CREATE POLICY "Admin full destinations" ON destinations USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full spots" ON photo_spots USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full nearby" ON nearby_places USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full page_sections" ON page_sections USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full articles" ON articles USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full checklists" ON checklists USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full playlists" ON playlists USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full playlist_items" ON playlist_items USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full newsletter" ON newsletter_subscribers USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full contact" ON contact_messages USING (auth.role() = 'authenticated');
