-- 1. DESTINATIONS MODULE
-- ==============================================================================

-- A. Core Upgrades to 'destinations' table
DO $$
BEGIN
    -- Basic Info & Metrics
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'trek_level') THEN
        ALTER TABLE destinations ADD COLUMN trek_level TEXT CHECK (trek_level IN ('Mudah', 'Sedang', 'Sulit', '-'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'season') THEN
        ALTER TABLE destinations ADD COLUMN season TEXT CHECK (season IN ('All Season', 'Kemarau', 'Hujan'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'visitor_percent') THEN
        ALTER TABLE destinations ADD COLUMN visitor_percent INTEGER DEFAULT 0;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'mood_tags') THEN
        ALTER TABLE destinations ADD COLUMN mood_tags TEXT[] DEFAULT '{}';
    END IF;

    -- Marketing Flags
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'is_trending') THEN
        ALTER TABLE destinations ADD COLUMN is_trending BOOLEAN DEFAULT FALSE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'is_recommended') THEN
        ALTER TABLE destinations ADD COLUMN is_recommended BOOLEAN DEFAULT FALSE;
    END IF;

    -- Detail Page Builder Config
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'detail_config') THEN
        ALTER TABLE destinations ADD COLUMN detail_config JSONB DEFAULT '{}'::jsonb;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'destinations' AND column_name = 'facilities') THEN
        ALTER TABLE destinations ADD COLUMN facilities TEXT[];
    END IF;
END $$;

-- B. Sub-tables for Destinations (Spots & Nearby)
CREATE TABLE IF NOT EXISTS photo_spots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT REFERENCES destinations(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    image_path TEXT,
    description TEXT,
    best_time TEXT,
    location_hint TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS nearby_places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT REFERENCES destinations(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT CHECK (type IN ('culinary', 'lodging', 'souvenir', 'basecamp', 'other')),
    distance TEXT,
    note TEXT,
    maps_url TEXT,
    image_path TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 2. PAGE & HOME MANAGEMENT
-- ==============================================================================
CREATE TABLE IF NOT EXISTS page_sections (
    section_key TEXT PRIMARY KEY, -- e.g. 'home_hero', 'home_districts', 'global_configs'
    content JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. TIPS & ARTICLES MODULE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    category TEXT DEFAULT 'Tips',
    cover_image TEXT,
    content TEXT,
    status TEXT DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS checklists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT REFERENCES articles(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    items JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 4. PLAYLISTS MODULE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS playlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    thumbnail_path TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS playlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id BIGINT REFERENCES playlists(id) ON DELETE CASCADE,
    destination_id BIGINT REFERENCES destinations(id) ON DELETE CASCADE,
    display_order INTEGER DEFAULT 0,
    UNIQUE(playlist_id, destination_id)
);

-- 5. USER INTERACTION MODULE
-- ==============================================================================
-- Newsletter
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    interests TEXT[] DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Contact Form
CREATE TABLE IF NOT EXISTS contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    subject TEXT,
    message TEXT NOT NULL,
    status TEXT DEFAULT 'new' CHECK (status IN ('new', 'read', 'replied')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Favorites (Collections)
CREATE TABLE IF NOT EXISTS favorites (
  user_id UUID REFERENCES auth.users NOT NULL,
  destination_id BIGINT REFERENCES destinations(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (user_id, destination_id)
);

-- User Roles (Admin/User)
CREATE TABLE IF NOT EXISTS user_roles (
  user_id UUID REFERENCES auth.users NOT NULL PRIMARY KEY,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);



